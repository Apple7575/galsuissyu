import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import {pathToFileURL} from 'node:url';
import {build} from 'esbuild';
import * as THREE from 'three';
const temp=path.resolve('scripts/.street-check-'+process.pid+'.mjs');
const originalFetch=globalThis.fetch;
let streets;
try{
 await build({entryPoints:['src/pilot-streets.ts'],outfile:temp,bundle:true,platform:'node',format:'esm',packages:'external',logLevel:'silent'});
 const {pilotStreets}=await import(pathToFileURL(temp).href);
 const source=JSON.parse(await fs.readFile('research/city/road.geojson','utf8'));
 const roads=source.features.filter(f=>f.id===26543334||f.id===28161122);
 assert(roads.length===2);
 let zoom=17;const requests=[];
 globalThis.fetch=async url=>{requests.push(url);return new Response(await fs.readFile('public'+url.split('?')[0]));};
 const map={getCenter:()=>({lng:127.432,lat:36.331}),getZoom:()=>zoom,getPitch:()=>52,getLayer:()=>true,queryRenderedFeatures:(_q,o)=>o.layers[0]==='city-roads'?roads:[],triggerRepaint(){}};
 const scene=new THREE.Scene();
 streets=pilotStreets(map,scene,c=>new THREE.Vector3((c[0]-127.432)*90000,(c[1]-36.331)*111000,0),()=>streets.refresh());
 streets.refresh();
 for(let i=0;i<100&&scene.children[0].children.filter(o=>o.isGroup).length<2;i++)await new Promise(r=>setTimeout(r,10));
 const root=scene.getObjectByName('pilot-street-reconstruction');
 assert(root.children.some(o=>o.isMesh),'Actual road geometry produces 3D surfaces');
 assert(root.children.some(o=>o.isGroup),'Existing GLBs are instanced on the map');
 assert.deepEqual(requests.sort(),['/data/static-scenery.json','/models/pilot/bus.glb','/models/pilot/lamp.glb','/models/pilot/tree.glb?v=foliage4']);
 const positions=()=>root.children.filter(o=>o.isGroup&&o.name).map(o=>[o.name,...o.position.toArray()]);
 const before=positions();assert(before.length>0,'Fixed street props exist');
 zoom=18;map.queryRenderedFeatures=()=>[];streets.refresh();
 assert.deepEqual(positions(),before,'Zoom/tile changes never relocate street props');
 streets.refresh();assert.equal(requests.length,4,'No repeat downloads');
 zoom=13;streets.refresh();assert(!root.visible);assert.equal(root.children.length,0);
 streets.dispose();assert.equal(scene.children.length,0);
 const startup=await fs.readFile('src/DaejeonMap.tsx','utf8');
 assert(startup.includes('onZoom(m.getZoom());startDetails();'),'Details start on style readiness, not citywide tile completion');
 const layer=await fs.readFile('src/city-miniatures.ts','utf8');
 assert(!layer.includes('!map.isStyleLoaded()'),'Optional geometry is not blocked by unrelated loading');
 console.log(JSON.stringify({actualRoadSurfaces:'passed',assetInstances:'passed',selectiveLoading:'passed',cleanup:'passed',startupGate:'passed'}));
}finally{streets?.dispose();globalThis.fetch=originalFetch;await fs.rm(temp,{force:true});}
